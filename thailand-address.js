const ThailandAddressLib = {
    getProvinces() {
        return Object.keys(THAILAND_ADDRESS_DATA).sort();
    },
    getDistricts(province) {
        if (!province || !THAILAND_ADDRESS_DATA[province]) return [];
        return Object.keys(THAILAND_ADDRESS_DATA[province]).sort();
    },
    getSubDistricts(province, district) {
        if (!province || !district || !THAILAND_ADDRESS_DATA[province] || !THAILAND_ADDRESS_DATA[province][district]) return [];
        return THAILAND_ADDRESS_DATA[province][district].sort();
    }
};

